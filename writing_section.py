RSS_FEEDS = {
    'BBC Sport': 'http://feeds.bbci.co.uk/sport/football/rss.xml',
    'Sky Sports': 'https://www.skysports.com/rss/12040',
    'The Guardian': 'https://www.theguardian.com/football/rss',
}

def scrape_news_articles():
    """Get latest football news from RSS feeds"""

    all_articles = []

    print("📰 Fetching news articles...\n")

    for source_name, feed_url in RSS_FEEDS.items():
        print(f"   📡 {source_name}...")

        try:
            feed = feedparser.parse(feed_url)

            if not feed.entries:
                print(f"      ⚠️ No entries\n")
                continue

            for entry in feed.entries[:10]:
                title = entry.get('title', 'No title')
                link = entry.get('link', '')
                description = entry.get('summary', entry.get('description', ''))

                # Clean HTML from description
                if description:
                    soup = BeautifulSoup(description, 'html.parser')
                    description = soup.get_text(strip=True)

                # Get date
                published = entry.get('published', 'Unknown date')
                try:
                    if hasattr(entry, 'published_parsed') and entry.published_parsed:
                        dt = datetime(*entry.published_parsed[:6])
                        published = dt.strftime('%Y-%m-%d %H:%M')
                except:
                    pass

                if len(title) < 10 or not link:
                    continue

                if any(a['url'] == link for a in all_articles):
                    continue

                all_articles.append({
                    'type': 'article',
                    'source': source_name,
                    'headline': title,
                    'url': link,
                    'preview': description[:150] if description else '',
                    'published': published,
                    'full_context': None  # Will fill if user selects
                })

            print(f"      ✅ {len([a for a in all_articles if a['source'] == source_name])} articles\n")

        except Exception as e:
            print(f"      ❌ Error: {str(e)[:50]}\n")

        time.sleep(0.5)

    return all_articles


def scrape_article_body(url):
    """Fetch full article text"""

    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'
    }

    print(f"   📄 Fetching article body...")

    try:
        response = requests.get(url, headers=headers, timeout=10)

        if response.status_code != 200:
            return None

        soup = BeautifulSoup(response.content, 'html.parser')

        # Try multiple selectors
        article_body = (
            soup.find('article') or
            soup.find('div', {'data-component': 'text-block'}) or
            soup.find('div', class_='article-body-commercial-selector') or
            soup.find('div', {'itemprop': 'articleBody'}) or
            soup.find('div', class_='sdc-article-body') or
            soup.find('div', class_='article__body')
        )

        if not article_body:
            return None

        paragraphs = article_body.find_all('p')

        article_text = []
        skip_phrases = ['cookie', 'subscribe', 'sign up', 'follow us', 'read more']

        for p in paragraphs:
            text = p.get_text(strip=True)
            if any(phrase in text.lower() for phrase in skip_phrases):
                continue
            if len(text) < 30:
                continue
            article_text.append(text)

        full_text = '\n\n'.join(article_text)

        headline = soup.find('h1')
        headline_text = headline.get_text(strip=True) if headline else 'Unknown'

        if len(full_text) < 200:
            return None

        print(f"      ✅ Extracted {len(full_text)} chars\n")

        return f"""SOURCE: News Article
HEADLINE: {headline_text}
URL: {url}

ARTICLE CONTENT:
{full_text[:2000]}"""

    except Exception as e:
        print(f"      ❌ Error: {str(e)[:50]}\n")
        return None


def scrape_all_matches_for_selection():
    """Get ALL matches in 2-day window and let user select"""
    all_matches = []

    today = datetime.now()
    start_date = (today - timedelta(days=1)).strftime('%Y%m%d')  # Yesterday
    end_date = (today + timedelta(days=1)).strftime('%Y%m%d')    # Tomorrow

    print(f"🔍 Fetching ALL matches from {start_date} to {end_date}...\n")

    leagues = {
        'eng.1': 'Premier League',
        'esp.1': 'La Liga',
        'ger.1': 'Bundesliga',
        'ita.1': 'Serie A',
        'fra.1': 'Ligue 1',
        'uefa.champions': 'Champions League',
        'eng.fa': 'FA Cup',
        'eng.league_cup': 'EFL Cup (Carabao)',
        'uefa.europa': 'Europa League',
        'uefa.europa.conf': 'Conference League',  # ← Added comma here
        'fifa.friendly': 'International Friendlies',
        'uefa.nations': 'Nations League',
        'conmebol.america': 'Copa America',
        'concacaf.gold': 'Gold Cup',
        'caf.afcon': 'African Cup of Nations',

    }


    for league_id, league_name in leagues.items():
        print(f"🔄 Fetching {league_name}...")

        try:
            url = f"https://site.api.espn.com/apis/site/v2/sports/soccer/{league_id}/scoreboard"
            params = {'dates': f'{start_date}-{end_date}', 'limit': 50}

            response = requests.get(url, params=params, timeout=10)
            if response.status_code != 200:
                print(f"   ⚠️ API error\n")
                continue

            data = response.json()
            events = data.get('events', [])

            if not events:
                print(f"   No matches found\n")
                continue

            for event in events:
                context = extract_match_context(event, league_id)

                home_team = context['basic_info']['home_team']
                away_team = context['basic_info']['away_team']

                if home_team == 'Unknown':
                    continue

                match_key = f"{home_team}_vs_{away_team}"

                # Check for duplicates
                if any(m['match_name'] == match_key for m in all_matches):
                    continue

                formatted_context = format_context_for_ai(context)

                all_matches.append({
                    'league': league_name,
                    'home_team': home_team,
                    'away_team': away_team,
                    'match_time': context['basic_info']['date'],
                    'status': context['basic_info']['status'],
                    'odds': 'N/A',
                    'match_name': match_key.replace(' ', '_'),
                    'event_id': context['basic_info']['event_id'],
                    'full_context': formatted_context
                })

                time.sleep(0.2)

            print(f"   ✅ Found {len([m for m in all_matches if m['league'] == league_name])} matches\n")

        except Exception as e:
            print(f"   ❌ Error: {str(e)[:50]}\n")

    return all_matches


