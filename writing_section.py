def fetch_match_details(event_id, league_id):
    """Fetch detailed match data from ESPN summary endpoint"""
    detail_url = f"https://site.api.espn.com/apis/site/v2/sports/soccer/{league_id}/summary"
    params = {'event': event_id}

    try:
        response = requests.get(detail_url, params=params, timeout=10)
        if response.status_code == 200:
            return response.json()
    except Exception as e:
        print(f"      ⚠️ Detail fetch error: {str(e)[:60]}")

    return None


def extract_match_context(event, league_id):
    """Extract ALL useful context from ESPN API response"""

    context = {
        'basic_info': {},
        'score': {},
        'events': [],
        'statistics': {},
        'records': {},
        'form': {},
        'commentary': [],
        'article': '',
    }

    # Basic info
    context['basic_info'] = {
        'event_id': event.get('id', ''),
        'name': event.get('name', ''),
        'date': event.get('date', ''),
        'status': event.get('status', {}).get('type', {}).get('description', 'Unknown')
    }

    comp = event.get('competitions', [{}])[0]
    competitors = comp.get('competitors', [])

    if len(competitors) < 2:
        return context

    # Teams
    home_comp = next((c for c in competitors if c.get('homeAway') == 'home'), competitors[0])
    away_comp = next((c for c in competitors if c.get('homeAway') == 'away'), competitors[1])

    home_team = home_comp.get('team', {}).get('displayName', 'Unknown')
    away_team = away_comp.get('team', {}).get('displayName', 'Unknown')

    context['basic_info']['home_team'] = home_team
    context['basic_info']['away_team'] = away_team

    # Score
    home_score = home_comp.get('score', 'N/A')
    away_score = away_comp.get('score', 'N/A')

    context['score'] = {
        'home': home_score,
        'away': away_score,
        'display': f"{home_team} {home_score} - {away_score} {away_team}"
    }

    # Match events (goals, cards)
    details = comp.get('details', [])
    for detail in details:
        event_type = detail.get('type', {}).get('text', 'Unknown')
        clock = detail.get('clock', {}).get('displayValue', 'Unknown')
        team_id = detail.get('team', {}).get('id', '')

        team_name = home_team if str(home_comp.get('team', {}).get('id')) == str(team_id) else away_team

        athletes = detail.get('athletesInvolved', [])
        player = athletes[0].get('displayName', 'Unknown') if athletes else 'Unknown'

        context['events'].append({
            'type': event_type,
            'time': clock,
            'team': team_name,
            'player': player,
            'is_goal': detail.get('scoringPlay', False)
        })

    # Statistics
    home_stats = home_comp.get('statistics', [])
    away_stats = away_comp.get('statistics', [])

    context['statistics']['home'] = {stat['name']: stat['displayValue'] for stat in home_stats}
    context['statistics']['away'] = {stat['name']: stat['displayValue'] for stat in away_stats}

    # Records
    home_records = home_comp.get('records', [])
    away_records = away_comp.get('records', [])

    if home_records:
        context['records']['home'] = home_records[0].get('summary', 'N/A')
    if away_records:
        context['records']['away'] = away_records[0].get('summary', 'N/A')

    # Form
    context['form']['home'] = home_comp.get('form', 'N/A')
    context['form']['away'] = away_comp.get('form', 'N/A')

    # Fetch detailed data
    event_id = event.get('id', '')
    if event_id:
        detail_data = fetch_match_details(event_id, league_id)

        if detail_data:
            # Commentary
            if 'commentary' in detail_data and isinstance(detail_data['commentary'], list):
                for item in detail_data['commentary'][:15]:
                    if isinstance(item, dict) and 'text' in item:
                        context['commentary'].append({
                            'time': item.get('time', {}).get('displayValue', ''),
                            'text': item.get('text', '')
                        })

            # Article
            if 'article' in detail_data:
                article = detail_data['article']
                if isinstance(article, dict) and 'story' in article:
                    # Strip HTML tags
                    import re
                    story = article['story']
                    story = re.sub('<[^<]+?>', '', story)  # Remove HTML
                    context['article'] = story[:1500]

    return context


def format_context_for_ai(context):
    """Format extracted context into readable text for AI"""

    output = []
    basic = context['basic_info']
    status = basic.get('status', 'Unknown')

    output.append(f"MATCH: {basic.get('home_team')} vs {basic.get('away_team')}")
    output.append(f"STATUS: {status}")
    output.append(f"DATE: {basic.get('date')}")

    # Only show score if match is finished
    is_finished = status in ['Full Time', 'FT', 'Final', 'STATUS_FINAL']

    if is_finished and context['score']['home'] != 'N/A':
        output.append(f"\nFINAL SCORE: {context['score']['display']}")

    # Season records
    if context['records'].get('home'):
        output.append(f"\nCURRENT SEASON RECORDS:")
        output.append(f"  {basic.get('home_team')}: {context['records'].get('home')}")
        output.append(f"  {basic.get('away_team')}: {context['records'].get('away')}")

    # Only include match events if finished
    if is_finished and context['events']:
        output.append(f"\nMATCH EVENTS:")
        for event in context['events'][:10]:
            emoji = "⚽" if event['is_goal'] else ("🟨" if "Yellow" in event['type'] else "🟥" if "Red" in event['type'] else "")
            output.append(f"  {emoji} {event['time']}: {event['player']} ({event['team']}) - {event['type']}")

    # Only include statistics if finished
    if is_finished and context['statistics'].get('home'):
        output.append(f"\nKEY STATISTICS:")

        stat_keys = ['possessionPct', 'totalShots', 'shotsOnTarget', 'foulsCommitted']

        for key in stat_keys:
            home_val = context['statistics']['home'].get(key, 'N/A')
            away_val = context['statistics']['away'].get(key, 'N/A')

            if home_val != 'N/A' and away_val != 'N/A':
                stat_name = key.replace('Pct', '%').replace('total', '').replace('Committed', '')
                output.append(f"  {stat_name}: {home_val} vs {away_val}")

    # Only include commentary if finished
    if is_finished and context['commentary']:
        output.append(f"\nCOMMENTARY HIGHLIGHTS:")
        for comm in context['commentary'][:8]:
            if comm['text']:
                output.append(f"  [{comm['time']}] {comm['text'][:120]}")

    # Only include article if finished
    if is_finished and context['article']:
        output.append(f"\nMATCH REPORT EXCERPT:")
        output.append(f"  {context['article'][:600]}")

    return "\n".join(output)

