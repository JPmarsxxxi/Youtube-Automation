def create_match_zip(match, mcp1, mcp2, mcp3, timestamp):
    """Create a zip file for one match with embedded instructions"""

    # Create filename
    if match.get('type') == 'article':
        safe_name = match['headline'][:40].replace(' ', '_').replace('/', '_').replace(':', '').replace('?', '').replace(',', '')
        zip_name = f"ARTICLE_{safe_name}_{timestamp}.zip"
    else:
        zip_name = f"{match['match_name']}_{timestamp}.zip"

    # Create instruction file content
    instruction_content = create_instruction_file(match, mcp1, mcp2, mcp3)

    # Create zip in memory
    zip_buffer = io.BytesIO()

    with zipfile.ZipFile(zip_buffer, 'w', zipfile.ZIP_DEFLATED) as zipf:
        # Add master instruction file
        zipf.writestr('INSTRUCTIONS_START_HERE.txt', instruction_content)

        # Add a quick reference file
        quick_ref = f"""QUICK START GUIDE
================

1. Attach this entire zip to Claude
2. Ask: "Follow the instructions in INSTRUCTIONS_START_HERE.txt"
3. Claude will do Stage 1 and stop
4. Review the output
5. Say "proceed" to move to Stage 2
6. Repeat for Stage 3

That's it! No copy/pasting needed.
"""
        zipf.writestr('QUICK_START.txt', quick_ref)

    zip_buffer.seek(0)
    return zip_name, zip_buffer.getvalue()


